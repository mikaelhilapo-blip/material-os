async function main() {
  const existing = await prisma.material.count({
    where: { source: 'SUPPLIER_LISTING' }
  })
  if (existing > 0) {
    console.log(`Seed skipped — ${existing} supplier listings already exist`)
    return
  }

  for (const m of sampleMaterials) {
    await prisma.material.create({
      data: { ...m, source: 'SUPPLIER_LISTING' }
    })
  }
  console.log(`Seeded ${sampleMaterials.length} sample materials`)
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
